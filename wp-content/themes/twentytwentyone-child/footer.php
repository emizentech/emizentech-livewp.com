    (function() {
        const utmParams = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content'];
        const storedUtmKey = 'utm_data';
        const expiryKey = 'utm_data_expiry';
        const EXPIRY_DAYS = 7;

        const urlParams = new URLSearchParams(window.location.search);
        const utmData = {};
        let hasNewUtm = false;

        // Parse UTM parameters from URL
        utmParams.forEach(param => {
            const value = urlParams.get(param);
            if (value) {
                utmData[param] = value;
                hasNewUtm = true;
            }
        });

        // Save UTM data and expiry time if any param found
        if (hasNewUtm) {
            const expiryTime = new Date().getTime() + EXPIRY_DAYS * 24 * 60 * 60 * 1000;
            localStorage.setItem(storedUtmKey, JSON.stringify(utmData));
            localStorage.setItem(expiryKey, expiryTime.toString());
        }

        // After DOM is ready, populate form fields if data is valid
        document.addEventListener('DOMContentLoaded', () => {
            const expiry = parseInt(localStorage.getItem(expiryKey) || '0', 10);
            const now = new Date().getTime();

            // If expired, clear data
            if (expiry && now > expiry) {
                localStorage.removeItem(storedUtmKey);
                localStorage.removeItem(expiryKey);
                return;
            }

            const savedUtm = JSON.parse(localStorage.getItem(storedUtmKey) || '{}');
            if (Object.keys(savedUtm).length === 0) return;

            // Fill form fields with matching ID format: form-field-utm_xxx
            utmParams.forEach(param => {
                const field = document.querySelector(`#form-field-${param}`);
                if (field && savedUtm[param]) {
                    field.value = savedUtm[param];
                }
            });
        });
    })();
</script>


