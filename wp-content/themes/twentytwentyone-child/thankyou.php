document.addEventListener("DOMContentLoaded", function () {

    const list = document.getElementById("whyList");

    // Stop if list not found
    if (!list) return;

    const items = Array.from(list.querySelectorAll("li"));

    // Sequential animation function
    function animateItem(index) {

        // Stop when all items animated
        if (index >= items.length) return;

        const li = items[index];

        // Enable transition class
        li.classList.add("animating");

        // Trigger animation properly
        requestAnimationFrame(() => {

            requestAnimationFrame(() => {

                li.classList.add("visible");

                // Wait for current item animation to finish
                const onTransitionEnd = (e) => {

                    // Only trigger for transform property
                    if (e.propertyName !== "transform") return;

                    li.removeEventListener("transitionend", onTransitionEnd);

                    // Animate next item
                    animateItem(index + 1);

                };

                li.addEventListener("transitionend", onTransitionEnd);

            });

        });

    }

    // Intersection Observer
    let triggered = false;

    const observer = new IntersectionObserver((entries) => {

        entries.forEach(entry => {

            if (entry.isIntersecting && !triggered) {

                triggered = true;

                // Start animation
                animateItem(0);

                // Stop observer after first trigger
                observer.disconnect();

            }

        });

    }, {
        threshold: 0.15
    });

    observer.observe(list);

});
